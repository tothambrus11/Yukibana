<?php

// Writes Phpactor's WorseSignatureHelper with one method changed, for
// phpactor.php to load in place of upstream's (build.sh):
//
//   php patch-signature-helper.php <upstream WorseSignatureHelper.php> <output>
//
// Upstream looks a called function up by its name as written: inside
// `distance($a, ` with `use function Geometry\distance;` it asks for a
// global `distance`, finds none, and gives no signature help, while hover,
// definition and completion (which resolve the name) find the function. The
// changed method looks it up the way PHP does: an imported or qualified name
// as resolved; an unqualified one in the current namespace, then globally.
//
// The method is replaced as text, and the build fails if upstream's method is
// not there exactly once, so a new Phpactor that changed it is noticed.

[, $from, $to] = $argv;

$old = <<<'PHP'
    private function signatureHelpForFunction(QualifiedName $callable, int $position): SignatureHelp
    {
        $name = $callable->__toString();
        $functionReflection = $this->reflector->reflectFunction($name);

        return $this->createSignatureHelp($functionReflection, $position);
    }
PHP;

$new = <<<'PHP'
    private function signatureHelpForFunction(QualifiedName $callable, int $position): SignatureHelp
    {
        // Yukibana (scripts/patch-signature-helper.php): the name as PHP
        // resolves it, not as written, so `use function` imports work.
        $resolved = $callable->getResolvedName();
        $names = $resolved !== null
            ? [$resolved->getFullyQualifiedNameText()]
            : [$callable->getNamespacedName()->getFullyQualifiedNameText(), $callable->getText()];
        $notFound = null;
        foreach (array_unique($names) as $name) {
            try {
                $functionReflection = $this->reflector->reflectFunction(ltrim($name, '\\'));
            } catch (NotFound $e) {
                $notFound ??= $e;
                continue;
            }

            return $this->createSignatureHelp($functionReflection, $position);
        }

        throw $notFound ?? new NotFound(sprintf('Function "%s" not found', $callable->getText()));
    }
PHP;

$source = file_get_contents($from);
if ($source === false || substr_count($source, $old) !== 1) {
    fwrite(STDERR, "$from: WorseSignatureHelper::signatureHelpForFunction is not upstream's any more; review the patch\n");
    exit(1);
}
$header = "<?php\n\n// Generated by packs/php/scripts/patch-signature-helper.php from Phpactor's\n"
    . "// lib/Completion/Bridge/TolerantParser/WorseReflection/WorseSignatureHelper.php.\n";
file_put_contents($to, preg_replace('/^<\?php\n/', $header, str_replace($old, $new, $source), 1));
