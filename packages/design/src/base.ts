/** Assembling css/base.css from its parts in css/base/, one file per component.
 *
 *  Consumers import one file, often into a cascade layer (`@import '…/base.css' layer(components)`), so the parts are
 *  concatenated into it rather than `@import`ed from it: a single file needs no bundler to follow nested imports. */

/** The parts, in cascade order: later parts may build on earlier ones, and the
 *  build refuses a file in css/base/ that is not listed here, so a new part cannot be forgotten. */
export const BASE_PARTS = [
    'core',
    'buttons',
    'chips',
    'fields',
    'check',
    'callout',
    'tabs',
    'dock',
    'code',
    'toast',
    'waiting',
    'lattice',
    'empty',
    'header',
    'table',
    'sidenav',
] as const;

/** One part: its name (the file is `css/base/<name>.css`) and its text. */
export interface BasePart {
    readonly name: string;
    readonly css: string;
}

/** css/base.css: a generated-file note, then each part under a comment naming its file. Line ends become LF, so a
 *  Windows checkout with CRLF parts builds the same bytes. */
export function concatBase(parts: readonly BasePart[]): string {
    const body = parts.map(p => `/* ---- css/base/${p.name}.css ---- */\n\n${p.css.replace(/\r\n/g, '\n').trim()}\n`);
    return [
        '/* Generated by packages/design/scripts/build.ts from the parts in css/base/. Do not edit: change a part and run `pnpm --filter @yukibana/design build`. */\n',
        ...body,
    ].join('\n');
}
